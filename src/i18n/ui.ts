export type Locale = "zh" | "en";

export const localeMeta: Record<Locale, { htmlLang: string; ogLocale: string }> = {
  zh: { htmlLang: "zh-CN", ogLocale: "zh_CN" },
  en: { htmlLang: "en", ogLocale: "en_US" },
};

/** Merge translated display fields over the shared factual fields (phone/email/…). */
export function getCompany(lang: Locale) {
  return lang === "en" ? { ...companyZh, ...companyEn } : companyZh;
}

/** Map a canonical (Chinese) path to a locale path. English pages live under /en/. */
export function toLocalePath(lang: Locale, zhPath: string) {
  if (lang === "zh") return zhPath;
  if (zhPath === "/") return "/en/";
  return "/en" + zhPath;
}

/**
 * Path of the same page in the other language, for the header language switcher.
 * Pages without a counterpart pass `alternate` explicitly (e.g. "/en/").
 * Note: with build.format "file", Astro.url.pathname at build time is the file path
 * ("/projects.html") — normalize back to the public directory URL form first.
 * Legacy archive paths under article//page//download/ genuinely keep their .html names.
 */
export function alternateLocalePath(pathname: string, alternate?: string) {
  if (alternate) return alternate;
  let p = pathname;
  if (p === "/index.html") p = "/";
  else if (p === "/en/index.html") p = "/en/";
  else if (p.endsWith(".html") && !/^\/(en\/)?(article|page|download)\//.test(p)) p = p.slice(0, -5) + "/";
  if (p === "/") return "/en/";
  if (p === "/en/") return "/";
  if (p.startsWith("/en/")) return p.slice(3);
  return "/en" + p;
}

